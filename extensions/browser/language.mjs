export function translator(language) {
  return (source, ...values) => {
    const text = language === 'en' && Object.hasOwn(english, source) ? english[source] : source;
    return values.length ? text.replace(/\{(\d+)\}/g, (_, index) => values[index] ?? '') : text;
  };
}

export function pageLabels(document) {
  const walker = document.createTreeWalker(document.documentElement, 4);
  const text = [];
  while (walker.nextNode()) {
    const node = walker.currentNode;
    if (/\p{Script=Han}/u.test(node.data)) text.push([node, node.data]);
  }
  const attributes = [];
  for (const element of document.querySelectorAll('[title], [aria-label], [alt], [placeholder]')) {
    for (const name of ['title', 'aria-label', 'alt', 'placeholder']) {
      const source = element.getAttribute(name);
      if (source && /\p{Script=Han}/u.test(source)) attributes.push([element, name, source]);
    }
  }
  return translate => {
    for (const [node, source] of text) node.data = source.replace(/\S(?:[\s\S]*\S)?/, translate(source.trim()));
    for (const [element, name, source] of attributes) element.setAttribute(name, translate(source));
  };
}
